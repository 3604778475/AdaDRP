    f.write('    assert norm > 0\n')
    f.write('    print("grad OK")\n\n')
    f.write('if __name__ == "__main__":\n')
    f.write('    test_q_mass()\n')
    f.write('    test_q_align()\n')
    f.write('    test_grad()\n')
