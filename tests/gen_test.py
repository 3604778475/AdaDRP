    f.write('    target_q = F.softmax(torch.randn(5, 8), dim=-1)\n')
    f.write('    loss, diag = q_align_loss(source_q, target_q)\n')
    f.write('    assert loss.item() >= 0\n')
    f.write('    print("q_align OK")\n\n')
    f.write('def test_grad():\n')
    f.write('    import torch.nn as nn\n')
    f.write('    model = nn.Linear(10, 1)\n')
