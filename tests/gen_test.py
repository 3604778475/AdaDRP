with open('/home/waas/MACB-DRP-main/tests/test_program_ot_repair.py', 'w') as f:
    f.write('"""Smoke tests for Phase 6-R."""\n')
    f.write('import sys\n')
    f.write('sys.path.insert(0, "/home/waas/MACB-DRP-main")\n')
    f.write('import torch\n')
    f.write('import torch.nn.functional as F\n')
    f.write('from adadrp.ot_utils import ProgramOTLoss, q_align_loss\n')
    f.write('from adadrp.grad_diagnostics import compute_grad_norm\n\n')
    f.write('def test_q_mass():\n')
    f.write('    source_z = torch.randn(4, 8, 64)\n')
    f.write('    source_q = F.softmax(torch.randn(4, 8), dim=-1)\n')
    f.write('    target_z = torch.randn(5, 8, 64)\n')
    f.write('    target_q = F.softmax(torch.randn(5, 8), dim=-1)\n')
    f.write('    module = ProgramOTLoss(mode="q_mass_flattened", lambda_program_ot=0.05)\n')
